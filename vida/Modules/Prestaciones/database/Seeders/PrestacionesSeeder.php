    public function run(): void
    {
        foreach ($this->prestaciones() as $data) {
            $tiposCentro = $data['tipos_centro'] ?? [];
            unset($data['tipos_centro']);

            $prestacion = Prestacion::updateOrCreate(
                ['codigo' => $data['codigo']],
                $data
            );

            // Sincronizar tipos de centro
            $prestacion->tiposCentro()->delete();
            foreach ($tiposCentro as $tipo) {
                $prestacion->tiposCentro()->create(['tipo_centro' => $tipo]);
            }
        }
    }

