/**
 * Catálogo inicial de prestaciones de servicios sociales.
 *
 * Basado en la Guía de Prestaciones de Servicios Sociales y Educativos
 * del Ayuntamiento de Madrid (edición 2024), que recoge 112 prestaciones
 * organizadas en ocho objetivos generales.
 *
 * Seeder idempotente: usa updateOrCreate por código. Puede ejecutarse
 * múltiples veces sin duplicados ni errores.
